"""Produce explicit synthetic before/after examples using the real JSON CLI.

No user media, model weights, external music or network is used. It is an effects
and orchestration verification, not a demonstration of cinematic storytelling.
"""
import argparse
import json
from pathlib import Path
import subprocess
import sys
from video_agent import media
from video_agent.store import write_json


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    root = Path(args.output).resolve()
    root.mkdir(parents=True, exist_ok=False)
    project = root / "project"
    calls = []
    def cli(*arguments):
        command = [sys.executable, "-m", "video_agent", *map(str, arguments)]
        result = subprocess.run(command, capture_output=True, text=True, timeout=180)
        calls.append({"argv": command, "exit_code": result.returncode})
        if result.returncode:
            raise RuntimeError(result.stderr)
        return json.loads(result.stdout)["result"]
    def task(kind, params):
        params_path = root / (str(len(calls)) + "-" + kind + ".json")
        write_json(params_path, params)
        return cli("run", "--project", project, "--task", kind, "--params", params_path)
    def aid(result, suffix):
        return next(a["id"] for a in result["artifacts"] if a["path"].endswith(suffix))
    source = root / "SYNTHETIC-before.mp4"
    # Deliberately visibly synthetic sources; distinct scenes exercise detection.
    media.ffmpeg(["-f", "lavfi", "-i", "testsrc2=size=480x270:rate=25:duration=3",
                  "-f", "lavfi", "-i", "smptebars=size=480x270:rate=25:duration=3",
                  "-f", "lavfi", "-i", "color=c=steelblue:size=480x270:rate=25:duration=3",
                  "-f", "lavfi", "-i", "sine=frequency=440:duration=9",
                  "-filter_complex", "[0:v][1:v][2:v]concat=n=3:v=1:a=0[v]", "-map", "[v]", "-map", "3:a:0",
                  "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac", "-t", "9", source])
    music = root / "SYNTHETIC-original-tone.wav"
    media.ffmpeg(["-f", "lavfi", "-i", "sine=frequency=220:duration=2", music])
    cli("init", "--project", project, "--input", source, "--name", "Synthetic effects verification, not real footage")
    analyzed = task("analyze_shots", {})
    analysis_id = aid(analyzed, "shot-analysis.json")
    suggestions = task("suggest_edit", {"analysis": analysis_id, "target_duration": 7, "max_segment_seconds": 3})
    track = task("import_subtitles", {"cues": [
        {"id": "a", "start_ms": 200, "end_ms": 2800, "text": "EXAMPLE DATA - Moving test pattern"},
        {"id": "b", "start_ms": 3200, "end_ms": 5800, "text": "EXAMPLE DATA - Colour bars"},
        {"id": "c", "start_ms": 6200, "end_ms": 8800, "text": "EXAMPLE DATA - Synthetic blue"}]})
    imported = task("import_music", {"file": str(music), "rights_confirmed": True, "license_note": "Synthetic original tone generated by this demo; no third-party music"})
    plan_params = {"segments": [
        {"sourceIn": 0, "sourceOut": 3, "reason": "Synthetic moving pattern: check opening fade"},
        {"sourceIn": 3, "sourceOut": 6, "reason": "Synthetic bars: check dissolve midpoint"},
        {"sourceIn": 6, "sourceOut": 9, "reason": "Synthetic still: check final fade"}],
        "analysis": analysis_id, "track": aid(track, "track.json"), "subtitle_mode": "soft",
        "transition": {"type": "fade", "duration": .6},
        "visual": {"look": "warm", "fade_in": .4, "fade_out": .6, "letterbox": .06},
        "music": {"artifact_id": aid(imported, ".wav"), "volume": .12, "ducking": True, "loop": True},
        "intent": "Explicitly synthetic effects demonstration; not a claim of film-quality editing"}
    plan = task("plan", plan_params)
    pid = aid(plan, "edit-plan.json")
    review = task("review_plan", {"plan": pid})
    preview = task("preview", {"plan": pid})
    # Approval is only for this programmatically generated test fixture.
    cli("approve", "--project", project, "--artifact", pid)
    rendered = task("render", {"plan": pid})
    video_item = next(a for a in rendered["artifacts"] if a["path"].endswith("subtitled.mp4"))
    video = project / video_item["path"]
    still = root / "SYNTHETIC-after.jpg"
    media.ffmpeg(["-ss", "2.6", "-i", video, "-frames:v", "1", still])
    report = {"fixture": "SYNTHETIC EXAMPLE DATA - test patterns and generated tones only",
              "purpose": "Real pipeline/effect verification, not aesthetic or semantic certification",
              "calls": calls, "analysis": analyzed, "suggestions": suggestions, "plan": plan,
              "review": review, "preview": preview, "render": rendered,
              "source": str(source), "output": str(video), "still": str(still),
              "expected_duration": 7.8, "hard_burn_executed": False,
              "actual_asr_or_music_selection": False}
    write_json(root / "report.json", report)
    print(json.dumps({"status": "passed", "source": str(source), "output": str(video), "still": str(still),
                      "report": str(root / "report.json"), "duration": rendered["detail"]["qc"]["media"]["duration"]}))


if __name__ == "__main__":
    main()
